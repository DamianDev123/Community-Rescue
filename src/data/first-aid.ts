function normalize(text: string) {
  return text.toLowerCase().trim();
}

/** Simple ranked search across title, keywords, and category — no network required. */
export function searchFirstAid(query: string): FirstAidTopic[] {
  const q = normalize(query);
  if (!q) return [];

  const scored = FIRST_AID_TOPICS.map((topic) => {
    const title = normalize(topic.title);
    let score = 0;

    if (title === q) score = 100;
    else if (title.startsWith(q)) score = 80;
    else if (title.includes(q)) score = 60;

    if (score === 0) {
      for (const keyword of topic.keywords) {
        const k = normalize(keyword);
        if (k === q) score = Math.max(score, 90);
        else if (k.startsWith(q)) score = Math.max(score, 70);
        else if (k.includes(q)) score = Math.max(score, 50);
      }
    }

    if (score === 0 && normalize(topic.category).includes(q)) score = 20;

    return { topic, score };
  });

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((s) => s.topic);
}
